const fs = require('fs');

let routeCode = fs.readFileSync('src/app/api/generate/route.ts', 'utf8');

const targetStr = '- **مدة كل فيديو (Duration):** احسب الثواني بدقة بحسب طول جملة المعلمة (معظمها 6 إلى 9 ثوانٍ) لمنع أي صمت ميت.\\n";';

const replacementStr = '- **مدة كل فيديو (Duration):** احسب الثواني بدقة بحسب طول جملة المعلمة (معظمها 6 إلى 9 ثوانٍ) لمنع أي صمت ميت.\\n" +\n' +
  '      "- **أسلوب الشرح ولغة الحوار (تبسيط علمي هادئ للأطفال 100% - تشرح بالراحة وبفهم):**\\n" +\n' +
  '      "  1. **الهدوء والوضوح (الشرح بالراحة وبفهم يوصل لأي طفل):** المعلمة تشرح خطوة واحدة دقيقة فقط في كل مشهد بنبرة حنونة، دافئة، ممتعة وهادئة (مثل برامج الأطفال العالمية). لا تجعلها تتحدث بسرعة أو حشو كلمات.\\n" +\n' +
  '      "  2. **ألفاظ مبسطة وتشبيهات بديهية جداً:** تجنب المصطلحات الجافة المعقدة! اشرح الفكرة بطريقة محسوسة يفهمها الطفل فوراً (مثال: بدلاً من المصطلحات الصعبة، قل: \\"شايفين الفلاتر الصغيرة دي يا أبطال؟ بتشتغل زي المصفاة بالضبط، تنزل الفضلات برة، وتحافظ على الدم النظيف يرجع لجسمنا بسرعة!\\").\\n" +\n' +
  '      "  3. **لغة عامية مصرية دافئة وراقية للأطفال:** استخدم كلمات رقيقة ومحفزة يفهمها الطلاب مثل (يا شطار، شوفوا معايا، بالراحة كدة، تبارك الله، جسمنا البطل). تجنب الفذلكة أو الكلمات الفصحى المعقدة.\\n" +\n' +
  '      "  4. **جمل قصيرة ومحكمة:** جملة أو جملتان في قمة البساطة والتركيز تصف ما يراه الطفل بعينيه الآن على الشاشة الذكية لترسخ المعلومة في عقله تماماً.\\n";';

routeCode = routeCode.replace(targetStr, replacementStr);

fs.writeFileSync('src/app/api/generate/route.ts', routeCode, 'utf8');
console.log('Successfully added simplified, calm, kid-friendly dialogue rules to paired mode!');
