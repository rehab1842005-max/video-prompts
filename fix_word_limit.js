const fs = require('fs');
let lines = fs.readFileSync('src/app/api/generate/route.ts', 'utf8').split('\n');

for (let i = 0; i < lines.length; i++) {
  if (lines[i].includes('3 جمل')) {
    lines[i] = lines[i].replace(/إجبار: شرح 3 جمل علمية على الأقل قبل السؤال/g, 'شرح مركز ومختصر جداً لعدم قطع الصوت');
    lines[i] = lines[i].replace(/يجب أن تقوم المعلمة بسرد \(3 جمل كاملة على الأقل\) تشرح فيها المعلومة العلمية المذكورة في النص بوضوح تام، المعلمة يجب أن تلقن المشاهدين المعلومة أولاً قبل أن تسأل الكرتون! إياك أن تطرح سؤالاً قبل أن تقول 3 جمل من الشرح التفصيلي! في آخر الجملة الثالثة فقط اطرح السؤال./g, 'يجب أن تشرح المعلمة المعلومة بوضوح وبدون تكرار في (جملة واحدة مركزة)، ثم تطرح سؤالاً قصيراً جداً. إجمالي كلام المعلمة يجب ألا يتخطى 20 كلمة أبداً حتى لا يُقطع الصوت في برنامج المونتاج!');
    lines[i] = lines[i].replace(/يجب أن تشرح المعلمة المعلومة العلمية بسرد \(3 جمل علمية على الأقل\) من النص المرفق. الكرتون غائب تماماً عن الشرح. إياك أن تطرح سؤالاً قبل أن تقدم شرحاً وافياً \(3 جمل على الأقل\). في آخر الفيديو اطرح السؤال./g, 'يجب أن تشرح المعلمة المعلومة بوضوح وبدون حشو أو تكرار في (جملة واحدة مركزة)، ثم في آخر ثانية تطرح سؤالاً قصيراً جداً للكرتون. إجمالي الحوار يجب ألا يتخطى 20 كلمة أبداً لكي لا ينقطع الصوت!');
    lines[i] = lines[i].replace(/\(3 جمل شرح أيضاً\)/g, '(جملة شرح واحدة قصيرة جداً)');
    lines[i] = lines[i].replace(/\(بـ 3 جمل جديدة\)/g, '(بجملة واحدة قصيرة جداً)');
  }
}

fs.writeFileSync('src/app/api/generate/route.ts', lines.join('\n'));
